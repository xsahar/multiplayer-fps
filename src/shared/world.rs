use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct World {
    pub width: usize,
    pub height: usize,
    pub tiles: Vec<Vec<u8>>,
    pub spawn_points: Vec<(f32, f32)>,
}

impl World {
    pub fn new(width: usize, height: usize, tiles: Vec<Vec<u8>>) -> Self {
        let mut spawn_points = Vec::new();
        for y in 0..height {
            for x in 0..width {
                if tiles[y][x] == 0 {
                    spawn_points.push((x as f32 + 0.5, y as f32 + 0.5));
                }
            }
        }

        Self {
            width,
            height,
            tiles,
            spawn_points,
        }
    }

    pub fn wall_at(&self, x: usize, y: usize) -> bool {
        if x >= self.width || y >= self.height {
            return true;
        }
        self.tiles[y][x] == 1
    }
}

